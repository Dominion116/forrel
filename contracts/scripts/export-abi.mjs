// Copy ForrelRegistry's ABI from forge's build output into @forrel/core as a typed `as const`
// array (so viem infers every function, event and error). Run after `forge build`:
//   npm --workspace=@forrel/contracts run abi
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const artifact = path.join(here, "..", "out", "ForrelRegistry.sol", "ForrelRegistry.json");
const target = path.join(here, "..", "..", "packages", "core", "src", "abi.ts");

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
const body = [
  "// Generated by contracts/scripts/export-abi.mjs from forge's build output. Do not edit by hand:",
  "// run `npm --workspace=@forrel/contracts run abi` after changing ForrelRegistry.sol.",
  "",
  `export const forrelRegistryAbi = ${JSON.stringify(abi, null, 2)} as const;`,
  "",
].join("\n");
writeFileSync(target, body);
console.log(`wrote ${path.relative(process.cwd(), target)} (${abi.length} entries)`);
